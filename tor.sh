#!/bin/bash
# Tor container entrypoint for MikroTik RouterOS containers.
#
# Runs Tor as a TRANSPARENT PROXY: it exposes a TransPort (transparent TCP) and
# a DNSPort so the router can redirect LAN traffic into Tor without any client
# configuration. .onion names resolve to a synthetic IP from Tor's
# VirtualAddrNetwork, and TCP to those synthetic IPs is carried into the Tor
# network. See the RouterOS scripts in yt/bgp-setup/tor-setup for the matching
# DNS-forward + dst-nat plumbing.
#
# Mirrors the structure of the tailscale-mikrotik container: an SSH server for
# management, host keys generated at first boot, and env-driven config.

set -m

# ---------------------------------------------------------------------------
# Env contract (all optional except where noted). Defaults suit the fabric.
# ---------------------------------------------------------------------------
#   PASSWORD          root password for the management SSH server (recommended)
#   TRANS_PORT        Tor TransPort           (default 9040)
#   DNS_PORT          Tor DNSPort             (default 9053)
#   SOCKS_PORT        Tor SOCKSPort           (default 9050; 0 disables)
#   VIRTUAL_ADDR_NET  VirtualAddrNetworkIPv4  (default 10.192.0.0/10)
#   LISTEN_ADDR       address Tor binds its ports on (default 0.0.0.0 so the
#                     router can reach them across the veth)
#   EXIT_NODES        optional Tor ExitNodes line value (e.g. "{us}")
#   EXTRA_TORRC       optional path to an extra torrc fragment to append
#   TOR_ARGS          optional extra args appended to the tor command line
# ---------------------------------------------------------------------------

TRANS_PORT="${TRANS_PORT:-9040}"
DNS_PORT="${DNS_PORT:-9053}"
SOCKS_PORT="${SOCKS_PORT:-9050}"
VIRTUAL_ADDR_NET="${VIRTUAL_ADDR_NET:-10.192.0.0/10}"
LISTEN_ADDR="${LISTEN_ADDR:-0.0.0.0}"

# Prepare run dirs
if [ ! -d "/var/run/sshd" ]; then
  mkdir -p /var/run/sshd
fi

# Generate SSH host keys on first start if missing (runtime, not build time —
# RSA keygen under arm/v5 emulation is unreliable, and per-container keys are
# better practice anyway; same rationale as the tailscale container).
if [ ! -f /etc/ssh/ssh_host_ed25519_key ]; then
  ssh-keygen -A
fi

# Set root password if provided
if [ -n "${PASSWORD:-}" ]; then
  echo "root:${PASSWORD}" | chpasswd
fi

# ---------------------------------------------------------------------------
# Build the effective torrc from the baked-in template + env overrides.
# The template lives at /etc/tor/torrc (copied in at build time). We generate a
# small override file so operators can also bind-mount their own torrc if they
# prefer. Tor reads torrc then the values here (last wins for single-line opts).
# ---------------------------------------------------------------------------
RUNTIME_TORRC="/var/lib/tor/torrc.runtime"
mkdir -p /var/lib/tor
chown -R debian-tor:debian-tor /var/lib/tor 2>/dev/null || true

{
  echo "# --- generated by tor.sh at container start ---"
  echo "DataDirectory /var/lib/tor"
  echo "SocksPort ${LISTEN_ADDR}:${SOCKS_PORT}"
  echo "DNSPort ${LISTEN_ADDR}:${DNS_PORT}"
  echo "TransPort ${LISTEN_ADDR}:${TRANS_PORT}"
  echo "VirtualAddrNetworkIPv4 ${VIRTUAL_ADDR_NET}"
  echo "AutomapHostsOnResolve 1"
  echo "AutomapHostsSuffixes .onion,.exit"
  if [ -n "${EXIT_NODES:-}" ]; then
    echo "ExitNodes ${EXIT_NODES}"
    echo "StrictNodes 1"
  fi
  if [ -n "${EXTRA_TORRC:-}" ] && [ -f "${EXTRA_TORRC}" ]; then
    echo "# --- appended from EXTRA_TORRC=${EXTRA_TORRC} ---"
    cat "${EXTRA_TORRC}"
  fi
} > "${RUNTIME_TORRC}"

echo "Effective runtime torrc:"
cat "${RUNTIME_TORRC}"

# Start the management SSH server in the background
/usr/sbin/sshd

# ---------------------------------------------------------------------------
# IN-CONTAINER TRANSPARENT REDIRECT (opt-in via TRANSPARENT_REDIRECT=Y)
# ---------------------------------------------------------------------------
# Tor's TransPort recovers a redirected connection's real destination via
# getsockopt(SO_ORIGINAL_DST). That only works if the netfilter REDIRECT/DNAT
# that rewrote the packet happened in the SAME network namespace Tor runs in.
# When the DNAT is done on the RouterOS host (a different netns), Tor logs
# "Fetching original destination failed. Closing." and drops every flow.
#
# The fix: do the REDIRECT *inside this container* so the conntrack entry Tor
# reads is local. For that:
#   - the host must ROUTE the Tor virtual range here with the destination IP
#     PRESERVED (no host DNAT), and
#   - we REDIRECT that range to TransPort locally, below.
# This requires the container to run with NET_ADMIN (RouterOS: privileged=yes).
#
# VIRTUAL_ADDR_NET is the range Tor hands out for .onion; we redirect TCP to it.
if [ "${TRANSPARENT_REDIRECT:-N}" = "Y" ]; then
  echo "TRANSPARENT_REDIRECT=Y: installing in-container REDIRECT for ${VIRTUAL_ADDR_NET} -> TransPort ${TRANS_PORT}"
  # Prove we actually have netfilter privileges; log clearly if not.
  if iptables -t nat -L >/dev/null 2>&1; then
    echo "iptables: nat table accessible (NET_ADMIN present)"
    # Redirect TCP destined to the Tor virtual range into the local TransPort.
    # REDIRECT (not DNAT) is what populates SO_ORIGINAL_DST for Tor.
    iptables -t nat -A PREROUTING -p tcp -d "${VIRTUAL_ADDR_NET}" \
      -j REDIRECT --to-ports "${TRANS_PORT}" \
      && echo "iptables: PREROUTING REDIRECT rule installed OK" \
      || echo "iptables: FAILED to install PREROUTING REDIRECT rule"
    echo "--- current nat/PREROUTING ---"
    iptables -t nat -S PREROUTING
  else
    echo "iptables: NAT TABLE NOT ACCESSIBLE — container lacks NET_ADMIN (needs privileged=yes). Transparent redirect will NOT work; use SOCKS instead."
  fi
fi

# ---------------------------------------------------------------------------
# Start Tor in the foreground. -f loads the base torrc which itself includes
# the runtime override via %include (see the baked /etc/tor/torrc).
# ---------------------------------------------------------------------------
exec tor -f /etc/tor/torrc ${TOR_ARGS:-}
